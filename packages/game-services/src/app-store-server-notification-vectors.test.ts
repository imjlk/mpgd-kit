import { describe, expect, it } from 'vitest';

import { createAppleServerNotificationVerifier } from './app-store-server.js';
import { handleAppStoreServerNotification } from './app-store-server-notifications.js';
import { createAppStoreVerificationId } from './app-store-verifier.js';
import { createInMemoryGameServicesStore } from './server.js';

// Real signature checks through Apple's library (no mocks). Apple publishes
// no signed notification vectors for third-party roots, so these JWS were
// signed once by a throwaway test CA whose chain carries Apple's marker
// extensions (1.2.840.113635.100.6.2.1 on the intermediate,
// 1.2.840.113635.100.6.11.1 on the leaf); only the root certificate below
// is trusted. The private keys were discarded. Offline checks use the
// sandbox environment, where Apple's verifier dates the chain at signedDate
// (2026-10-25T02:00:00Z); production verification requires online OCSP.

const bundleId = 'dev.mpgd.vectors';
const transactionId = '2000000900000001';

function verifier() {
  return createAppleServerNotificationVerifier({
    rootCertificates: [Uint8Array.from(Buffer.from(trustedRootBase64, 'base64'))],
    environment: 'Sandbox',
    bundleId,
    enableOnlineChecks: false,
  });
}

function verify(signedPayload: string) {
  return verifier().verifyAndDecodeNotification({
    signedPayload,
    environment: 'Sandbox',
    bundleId,
    signal: new AbortController().signal,
  });
}

describe('App Store Server Notifications V2 vectors', () => {
  it('verifies a refund and its signed transaction against the trusted root', async () => {
    const result = await verify(refundNotification);
    expect(result).toMatchObject({
      status: 'verified',
      notification: {
        notificationType: 'REFUND',
        notificationUUID: '7f3c1d52-2b7e-4f0e-9a51-0d7d4e6b8a01',
        environment: 'Sandbox',
        bundleId,
        transaction: {
          transactionId,
          type: 'Consumable',
          environment: 'Sandbox',
          inAppOwnershipType: 'PURCHASED',
          revocationDate: Date.parse('2026-10-25T01:59:00.000Z'),
        },
      },
    });
  });

  it('verifies a TEST notification without a transaction', async () => {
    const result = await verify(testNotification);
    expect(result.status).toBe('verified');
    if (result.status === 'verified') {
      expect(result.notification.notificationType).toBe('TEST');
      expect(result.notification.transaction).toBeUndefined();
    }
  });

  it('verifies a data-less SUMMARY notification so the handler can ignore it with 200', async () => {
    const result = await verify(summaryNotification);
    expect(result).toEqual({
      status: 'verified',
      notification: {
        notificationType: 'RENEWAL_EXTENSION',
        subtype: 'SUMMARY',
        notificationUUID: '5d1a7c3e-6b24-4c8f-9e0a-2f7b8c9d0e11',
        signedDate: Date.parse('2026-10-25T02:00:00.000Z'),
        environment: 'Sandbox',
        bundleId,
      },
    });
    const outcome = await handleAppStoreServerNotification({
      store: createInMemoryGameServicesStore(),
      verifier: verifier(),
      body: { signedPayload: summaryNotification },
      environment: 'Sandbox',
      bundleId,
      signal: new AbortController().signal,
    });
    expect(outcome).toEqual({
      status: 'ignored',
      reason: 'APP_STORE_NOTIFICATION_TYPE_UNHANDLED',
      notificationUUID: '5d1a7c3e-6b24-4c8f-9e0a-2f7b8c9d0e11',
    });
  });

  it('refuses a chain that does not end at a trusted root, and a tampered payload', async () => {
    expect(await verify(rogueNotification)).toEqual({
      status: 'rejected', reason: 'APP_STORE_SIGNATURE_INVALID',
    });
    expect(await verify(tamperedNotification)).toEqual({
      status: 'rejected', reason: 'APP_STORE_SIGNATURE_INVALID',
    });
  });

  it('refuses a data-less notification of another app', async () => {
    expect(await verify(otherAppSummaryNotification)).toEqual({
      status: 'rejected', reason: 'APP_STORE_SIGNATURE_INVALID',
    });
  });

  it('names a rejected embedded transaction apart from the payload', async () => {
    expect(await verify(untrustedTransactionNotification)).toEqual({
      status: 'rejected', reason: 'APP_STORE_NOTIFICATION_TRANSACTION_SIGNATURE_INVALID',
    });
  });

  it('names a notification of the other environment', async () => {
    expect(await verify(productionNotification)).toEqual({
      status: 'rejected', reason: 'APP_STORE_ENVIRONMENT_MISMATCH',
    });
  });

  it('revokes the sandbox grant a production deployment recorded for App Review', async () => {
    const store = createInMemoryGameServicesStore();
    const grant = await store.recordEntitlementGrant({
      source: 'purchase',
      playerId: 'player-1',
      grantId: 'COINS_100',
      idempotencyKey: 'checkout-1',
      grantedAt: '2026-10-25T01:00:00.000Z',
      evidenceVerificationId: createAppStoreVerificationId({
        environment: 'Sandbox',
        bundleId,
        transactionId,
      }),
      payload: { target: 'ios', store: 'app-store', appStoreEnvironment: 'Sandbox' },
    });
    const handle = () => handleAppStoreServerNotification({
      store,
      verifier: verifier(),
      body: { signedPayload: refundNotification },
      environment: 'Sandbox',
      bundleId,
      signal: new AbortController().signal,
    });
    const first = await handle();
    expect(first).toMatchObject({ status: 'revoked', alreadyProcessed: false });
    expect(await handle()).toMatchObject({ status: 'revoked', alreadyProcessed: true });
    const [revocation] = await store.findEntitlementRevocations({
      ledgerEntryIds: [grant.ledgerEntryId],
    });
    expect(revocation).toMatchObject({
      reason: 'refund',
      revokedAt: '2026-10-25T01:59:00.000Z',
      idempotencyKey: 'app-store:notification:7f3c1d52-2b7e-4f0e-9a51-0d7d4e6b8a01',
    });
  });
});

